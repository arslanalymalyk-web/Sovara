// Generates src/lib/rbac/data.generated.ts from the prototype's rbac.js (the executable specification).
// `npm run check` fails if the committed file differs, so the server and the prototype cannot drift apart.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const rbac = require(path.resolve(here, '../../rgs-portal/rbac.js'));

const out = `// GENERATED by scripts/generate-rbac-data.mjs from rgs-portal/rbac.js. Do not edit by hand.
// Regenerate with \`npm run sync:rbac\`.
/* eslint-disable */
export const SERVICES = ${JSON.stringify(rbac.SERVICES)} as const;
export const PROJECT_TYPES = ${JSON.stringify(rbac.PROJECT_TYPES)} as const;
export const ACTION_DEFS = ${JSON.stringify(rbac.ACTIONS, null, 2)} as const;
export const ROLE_DEFS = ${JSON.stringify(rbac.ROLES, null, 2)} as const;
export const ROLE_ORDER = ${JSON.stringify(rbac.ROLE_ORDER)} as const;
export const AI_SAFE_ACTIONS = ${JSON.stringify(rbac.AI_SAFE_ACTIONS)} as const;
`;
writeFileSync(path.resolve(here, '../src/lib/rbac/data.generated.ts'), out);
console.log('rbac data written:', Object.keys(rbac.ACTIONS).length, 'actions,', rbac.ROLE_ORDER.length, 'roles');
